# [코드 1] 평균이라는 손실 압축: 정반대 구조인 두 부서의 평균이 똑같다
# 1장 02절에서 확정한 표준 셋업 스니펫이 실행된 상태를 전제합니다.

import numpy as np

# A부서: 팀원 10명이 정확히 500만 원씩 수령하는 균등 보상 구조
salary_A = np.array([500] * 10)

# B부서: 팀장 1명이 4,100만 원을 독식하고, 팀원 9명은 100만 원씩 수령하는 착취 구조
salary_B = np.array([4100] + [100] * 9)

# 평균 급여 출력
print(f"A부서 평균 급여: {salary_A.mean():.1f}만 원")
print(f"B부서 평균 급여: {salary_B.mean():.1f}만 원")
